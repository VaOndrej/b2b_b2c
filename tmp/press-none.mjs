import { chromium } from '@playwright/test';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
await p.goto('http://127.0.0.1:9292/', { waitUntil: 'load' });
await p.waitForTimeout(1500);
const el = p.locator('a.won-fx, button.won-fx').first();
await el.scrollIntoViewIfNeeded();
await el.evaluate((n) => n.setAttribute('data-fx-probe', '1'));
const read = () => p.evaluate(() => getComputedStyle(document.querySelector('[data-fx-probe]')).transform);
const cls = await el.evaluate((n) => n.className);
await el.hover(); await p.waitForTimeout(400);
const hover = await read();
const box = await el.boundingBox();
await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
await p.mouse.down(); await p.waitForTimeout(300);
const press = await read();
await p.mouse.up();
console.log('třídy :', cls);
console.log('hover :', hover);
console.log('press :', press);
console.log(press === hover ? 'OK — press=none nic nemění' : 'NÁLEZ — press=none přesto mění transform');
await b.close();
