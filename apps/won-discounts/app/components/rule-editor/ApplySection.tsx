// Section 3 "Jak se uplatní": automatically or with codes, and — for a code
// rule only (Shopify counts uses of codes, nothing else) — the usage limits.
// An automatic rule shows no limits at all (P2). P3: a code rule without a code
// is marked at the codes field from the live draft. P5: the cap on active code
// rules counts the draft as it is now and is said only when it is close.
//
// The codes are one block (`codes`), the limits another: the code generator and
// the code list (a later wave) replace the text area inside the first.

import { useEffect, useRef, useState } from "react";

import { ruleHasCodes, type CodeBatchSpec } from "@won/core/discounts/code-batch";

import { CONFIG_LIMITS } from "@won/core/discounts/config";

import { useT } from "../../i18n/context";
import { describeLimits, describeMethod } from "../model/describe";
import { FIELD } from "../model/rule-form";
import type { CodeRuleLimit, GeneratedBatchView } from "../model/types";
import { boolAttr } from "../shell/attrs";
import { SegmentedChoice } from "../shell/SegmentedChoice";
import { RowNote, WonSection } from "../shell/WonSection";
import { WON_FONT, WON_INK, WON_MUTED, WON_SELECT, WON_SURFACE } from "../shell/tokens";
import { EDITOR_STEPS } from "./steps";
import { CodeGenerator, GeneratedBatches } from "./GeneratedCodes";
import { FieldMark, Shown, type EditorView } from "./parts";

/** From this share of the cap on, the editor and the list say how many code rules are on. */
export const CODE_LIMIT_NEAR = 0.8;

export function codeLimitNear(limit: CodeRuleLimit): boolean {
  return limit.limit > 0 && limit.active >= limit.limit * CODE_LIMIT_NEAR;
}

/**
 * How the codes of a code discount come to be (13 Oct 2026): one way at a time — typed by the merchant, a batch
 * generated by the app, or a single random code. The choice only decides which fields are shown; codes and
 * batches the discount already has stay (and are listed) whichever way is picked.
 */
export type CodeMode = "manual" | "batch" | "random";
export const CODE_MODES: readonly CodeMode[] = ["manual", "batch", "random"];

function CodeModeTiles({ mode, onPick, disabled }: { mode: CodeMode; onPick: (mode: CodeMode) => void; disabled: boolean }) {
  const { t } = useT();
  return (
    <div data-won-code-modes="" role="group" aria-label={t("editor.codes.mode.label")} style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(190px, 1fr))", gap: 10, fontFamily: WON_FONT }}>
      {CODE_MODES.map((value) => {
        const selected = value === mode;
        return (
          <button
            key={value}
            type="button"
            data-won-code-mode={value}
            aria-pressed={selected}
            disabled={disabled}
            onClick={() => onPick(value)}
            style={{ textAlign: "left", padding: selected ? "11px 13px" : "12px 14px", borderRadius: 12, border: selected ? `2px solid ${WON_SELECT}` : "1px solid #d6dbe1", background: selected ? "#f2f7ff" : WON_SURFACE, cursor: disabled ? "not-allowed" : "pointer", font: "inherit", display: "grid", gap: 3 }}
          >
            <span style={{ fontSize: 14, fontWeight: 700, color: WON_INK }}>{t(`editor.codes.mode.${value}`)}</span>
            <span style={{ fontSize: 12.5, lineHeight: 1.4, color: WON_MUTED }}>{t(`editor.codes.mode.${value}.about`)}</span>
          </button>
        );
      })}
    </div>
  );
}

export function ApplySection({
  ed,
  codeRules,
  pro,
  batches,
  pendingBatch,
}: {
  ed: EditorView;
  codeRules: CodeRuleLimit;
  /** Server-derived Pro entitlement: the generator's pattern fields. */
  pro: boolean;
  /** The generated batches the stored rule has, with their codes. */
  batches: readonly GeneratedBatchView[];
  /** The generator's live spec, when a count is typed: codes will be made on save. */
  pendingBatch?: CodeBatchSpec;
}) {
  const { draft, defaults, errorFor, tr, readOnly } = ed;
  const { t } = tr;
  const off = boolAttr(readOnly);
  const isCode = draft.method === "code";
  const noCode = isCode && !ruleHasCodes(draft) && !pendingBatch;
  const hasOwn = defaults.codes.trim() !== "";
  // A count already in the form (a refused save came back with it) keeps its way open.
  const [mode, setMode] = useState<CodeMode>(() => (pendingBatch ? (pendingBatch.count === 1 ? "random" : "batch") : batches.length > 0 ? "batch" : "manual"));
  // The fields of the way picked appear or go: the form is told, so the editor reads it again (and the save bar shows).
  const rootRef = useRef<HTMLDivElement>(null);
  const mounted = useRef(false);
  useEffect(() => {
    if (mounted.current) rootRef.current?.closest("form")?.dispatchEvent(new Event("change", { bubbles: true }));
    mounted.current = true;
  }, [mode]);
  return (
    <WonSection step={{ n: 3, of: EDITOR_STEPS }}
      title={t("editor.section.apply")}
      glyph="code"
      summary={[describeMethod(draft, tr), describeLimits(draft, tr)].filter(Boolean).join(" · ")}
      hint={isCode && codeLimitNear(codeRules) ? t("editor.codeLimit", { active: codeRules.active, limit: codeRules.limit }) : undefined}
      anchor="codes"
    >
      <s-stack direction="block" gap="base">
        <SegmentedChoice
          name={FIELD.method}
          label={t("editor.method.label")}
          defaultValue={defaults.method}
          disabled={readOnly}
          options={[
            { value: "automatic", label: t("editor.method.automatic") },
            { value: "code", label: t("editor.method.code") },
          ]}
        />
        <Shown when={isCode}>
          <s-stack direction="block" gap="base">
            <div ref={rootRef}>
              <CodeModeTiles mode={mode} onPick={setMode} disabled={readOnly} />
              {noCode ? <FieldMark text={t("editor.mark.noCode")} /> : null}
            </div>
            {/* Always in the form (codes the discount has are never dropped by picking another way), shown for "manual". */}
            <Shown when={mode === "manual"}>
              <s-text-area
                name={FIELD.codes}
                label={t("editor.codes.own")}
                value={defaults.codes}
                rows={3}
                details={t("editor.codes.details")}
                error={errorFor(FIELD.codes)}
                disabled={off}
              />
            </Shown>
            {mode !== "manual" && hasOwn ? <RowNote>{t("editor.codes.mode.ownKept", { codes: defaults.codes.trim().split(/\s+/).join(", ") })}</RowNote> : null}
            {mode === "batch" ? <CodeGenerator pro={pro} pending={pendingBatch} batchCount={draft.codeBatches?.length ?? 0} disabled={readOnly} errorFor={errorFor} /> : null}
            {mode === "random" ? (
              <div data-won-code-random="">
                {(draft.codeBatches?.length ?? 0) >= CONFIG_LIMITS.codeBatchesPerRule ? (
                  <RowNote>{t("editor.generate.full", { max: CONFIG_LIMITS.codeBatchesPerRule })}</RowNote>
                ) : (
                  <>
                    <input type="hidden" name={FIELD.batchCount} value="1" />
                    <RowNote>{t("editor.codes.mode.random.how")}</RowNote>
                    <FieldMark text={errorFor(FIELD.batchCount)} />
                  </>
                )}
              </div>
            ) : null}
            <GeneratedBatches batches={batches} disabled={readOnly} />
            <s-stack direction="block" gap="small-200">
              <s-number-field
                name={FIELD.usageLimit}
                label={t("editor.limits.usage")}
                value={defaults.usageLimit}
                min={1}
                inputMode="numeric"
                details={t("editor.limits.usageDetails")}
                error={errorFor(FIELD.usageLimit)}
                disabled={off}
              />
              <s-checkbox name={FIELD.oncePerCustomer} value="on" label={t("editor.limits.once")} checked={boolAttr(defaults.oncePerCustomer)} disabled={off} />
            </s-stack>
          </s-stack>
        </Shown>
      </s-stack>
    </WonSection>
  );
}
