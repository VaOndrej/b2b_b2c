#!/usr/bin/env node
/* eslint-env node */
// Postgres port (MVP 7, contract M10). The app is developed and unit-tested on SQLite (prisma/schema.prisma, the
// committed migrations); production runs Postgres. This script derives the Postgres side from the SQLite schema so
// the two never drift:
//   prisma/postgres/schema.prisma                  the same models, provider "postgresql";
//   prisma/postgres/migrations/0001_init/…         one baseline migration: `prisma migrate diff` from empty to that
//                                                  schema (offline, no database) + the indexes Prisma's schema
//                                                  language cannot express (PARTIAL_INDEXES below, hand-ported
//                                                  from the SQLite migrations);
//   prisma/postgres/migrations/migration_lock.toml provider = "postgresql".
//   node scripts/make-postgres-schema.mjs           write them
//   node scripts/make-postgres-schema.mjs --check   exit 1 when the committed files differ (tests/lib/postgres-schema.test.ts)
// The Dockerfile copies prisma/postgres over prisma/ before `prisma generate`, so the image's client and
// `prisma migrate deploy` (fly.toml release_command) are Postgres. While nothing is deployed the baseline is
// regenerated in place; after the first deploy a schema change needs a NEW migration next to it.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SQLITE_SCHEMA = path.join(APP, "prisma/schema.prisma");
const OUT_DIR = path.join(APP, "prisma/postgres");
const SCHEMA = path.join(OUT_DIR, "schema.prisma");
const MIGRATION = path.join(OUT_DIR, "migrations/0001_init/migration.sql");
const LOCK = path.join(OUT_DIR, "migrations/migration_lock.toml");

// Hand-ported from prisma/migrations/20260928184219_sync_version_link_claim_guard (a partial unique index: at
// most one live claim per native discount; app/lib/native/move.server.ts treats its violation as "already claimed").
const PARTIAL_INDEXES = `
-- Partial unique index (not expressible in schema.prisma): one live claim per native discount.
CREATE UNIQUE INDEX "NativeDiscountBackup_one_claim_per_native"
    ON "NativeDiscountBackup"("shop", "nativeId") WHERE "status" IN ('moving', 'undoing');
`;

export function postgresSchema(sqlite) {
  const out = sqlite
    .replace(/provider = "sqlite"/, 'provider = "postgresql"')
    .replace('output       = "../app/generated/prisma"', 'output       = "../../app/generated/prisma"');
  if (out === sqlite || !out.includes('provider = "postgresql"') || !out.includes("../../app/generated/prisma")) throw new Error("prisma/schema.prisma no longer has the lines this script rewrites");
  return `// GENERATED by scripts/make-postgres-schema.mjs from prisma/schema.prisma — DO NOT EDIT.\n${out}`;
}

function build() {
  const schema = postgresSchema(fs.readFileSync(SQLITE_SCHEMA, "utf8"));
  const tmp = fs.mkdtempSync(path.join(APP, "prisma/.pg-"));
  try {
    // The same relative depth as prisma/postgres/, so the generator's output path stays valid for Prisma's parser.
    const tmpSchema = path.join(tmp, "schema.prisma");
    fs.writeFileSync(tmpSchema, schema);
    const sql = execFileSync("npx", ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", tmpSchema, "--script"], { cwd: APP, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
    return {
      [SCHEMA]: schema,
      [MIGRATION]: `-- GENERATED by scripts/make-postgres-schema.mjs (prisma migrate diff from empty) — the Postgres baseline.\n${sql.trimEnd()}\n${PARTIAL_INDEXES}`,
      [LOCK]: '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
    };
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = build();
  const check = process.argv.includes("--check");
  let drift = 0;
  for (const [file, content] of Object.entries(files)) {
    const rel = path.relative(APP, file);
    if (check) {
      const same = fs.existsSync(file) && fs.readFileSync(file, "utf8") === content;
      console.log(`${same ? "✓" : "✗"} ${rel}`);
      if (!same) drift += 1;
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
      console.log(`wrote ${rel}`);
    }
  }
  if (drift) {
    console.error("Postgres schema is stale: run `node scripts/make-postgres-schema.mjs`");
    process.exit(1);
  }
}
